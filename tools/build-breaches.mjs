// Data from Have I Been Pwned, licensed CC BY 4.0: https://haveibeenpwned.com/ . Run monthly: node tools/build-breaches.mjs
import fs from 'fs';
const res = await fetch('https://haveibeenpwned.com/api/v3/breaches', { headers: { 'user-agent': 'VPNInsights-Shield-list-build' } });
if (!res.ok) { console.error('HIBP answered', res.status); process.exit(1); }
const all = await res.json();
const map = {};
for (const b of all) {
  if (!b.Domain || !b.IsVerified || b.IsSpamList || b.IsFabricated || b.IsSensitive || (b.PwnCount || 0) < 100000) continue;
  const d = String(b.Domain).toLowerCase().replace(/^www\./, '');
  const year = Number(String(b.BreachDate).slice(0, 4)) || 0;
  const cur = map[d];
  if (!cur || year > cur[1]) map[d] = [b.Title || b.Name, year, b.PwnCount];
}
const keys = Object.keys(map).sort(); const sorted = {}; for (const k of keys) sorted[k] = map[k];
fs.writeFileSync(new URL('../src/breaches.js', import.meta.url), `// Generated by tools/build-breaches.mjs from Have I Been Pwned (CC BY 4.0). Do not edit.\n// Shape: domain -> [breach name, year, accounts]\nconst SHIELD_BREACHES = ${JSON.stringify(sorted)};\nconst SHIELD_BREACHES_BUILT = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n`);
console.log('breached sites:', keys.length, 'of', all.length, 'listed');
